/* 名所が手薄だった町の作り込み (その3)
   - 渋谷: 金王八幡宮 (渋谷氏の城跡に建つ八幡宮。1612年の社殿)
   - 麻布: 善福寺 (最初のアメリカ公使館跡・逆さイチョウ) と麻布十番商店街
   - 白金台: 明治学院 (記念館・インブリー館・礼拝堂) / 高輪: 東禅寺 (最初のイギリス公使館跡) */
REGION({
  name: '渋谷東・麻布・白金高輪',
  towns: [['渋谷三丁目', -2766, -50], ['元麻布', -1940, -30], ['麻布十番', -1830, -120], ['白金台一丁目', -1600, 980], ['高輪三丁目', -1470, 1115], ['赤坂六丁目', -1760, -1190]],
  labels: [],
  build(r) {
    const { C, site, spot, sign, SHU, STONE, plasterWood, windows, hall, gate, street } = SL_KIT();
    const trees = (R, n, list = ROUND, avoid = null, s0 = 0.8, s1 = 1.2, base) => {
      for (let k = 0; k < n; k++) { const x = rr(R[0] + 2, R[2] - 2), z = rr(R[1] + 2, R[3] - 2); if (avoid && avoid(x, z)) continue; list.push(base === undefined ? [x, z, rr(s0, s1)] : [x, z, rr(s0, s1), base]); }
    };

    // ===== 金王八幡宮 (渋谷城の跡。春日局らが寄進した極彩色の社殿) =====
    {
      const R = [-2786, -127, -2738, -73];
      site(R, '#c2baa6');
      myojinTorii(-2762, -77, true, 5.5, 6, STONE, 0.34);
      gate([-2772, -97, -2752, -91], 6, 'RF_COPPER', 3.2);   // 門
      const GOK = LM_MAT('KO_GOKUSAI', (x, y) => {   // 極彩色の社殿
        x.fillStyle = '#b83a2a'; x.fillRect(0, 0, 32, 32); y.fillStyle = '#000'; y.fillRect(0, 0, 32, 32);
        for (const [c, yy] of [['#2a6a4a', 2], ['#e8c040', 8], ['#2a4a8a', 14], ['#f0f0e8', 20]]) { x.fillStyle = c; for (let i = 0; i < 32; i += 6) x.fillRect(i, yy, 4, 3); }
      });
      hall([-2776, -121, -2748, -105], GOK, 0.6, 5, 'RF_COPPER', 4.6);
      pushPrism('TKSTONE', 'TKSTONE', rectPoly(-2778, -123, -2746, -103), 0, 0.6);
      for (const [x, z] of [[-2782, -85], [-2742, -115]]) pushPrism('ISHIGAKI', 'ISHIGAKI', rectPoly(x - 1.6, z - 1, x + 1.6, z + 1), 0, 1.2);   // 渋谷城の砦の石
      SAKURA.push([-2780, -95, 1], [-2744, -95, 0.9]);   // 金王桜
      trees(R, 6, GINKGO, (x, z) => Math.abs(x + 2762) < 14);
      spot('金王八幡宮', R, '金王八幡宮', '⛩', '1092年創建と伝わる、渋谷と青山の総鎮守。この神社を中心に渋谷氏が「渋谷城」を築き、それが「渋谷」の地名のもとともいわれる。いまの社殿は1612年の建築で、春日局らの寄進によるもの。境内には城の砦の石も残る', -2762, -105);
    }

    // ===== 麻布: 善福寺 (逆さイチョウ) と麻布十番商店街 =====
    {
      const R = [-1956, -101, -1904, -49];
      site(R, '#c2baa6');
      gate([-1940, -57, -1920, -51], 6, 'RF2', 3.4);   // 山門
      hall([-1946, -93, -1914, -73], 'WOOD', 0.8, 6.5, 'RF2', 6);
      pushPrism('TKSTONE', 'TKSTONE', rectPoly(-1948, -95, -1912, -71), 0, 0.8);
      GINKGO.push([-1912, -61, 2.4]); solid(-1913, -62, -1911, -60, 0, 8);   // 逆さイチョウ
      spot('善福寺 (麻布)', R, '善福寺', '🍂', '都内でも古い寺のひとつで、幕末には最初のアメリカ公使館が置かれ、ハリスが暮らした。境内の大イチョウは、親鸞がついた杖が根づいたという伝説から「逆さイチョウ」と呼ばれる国の天然記念物', -1930, -80);
      const F = frame(-1900, -150, 1, 0, 0, 1);
      street(F, 140, { hw: 4, c1: '#c8c2b6', c2: '#b4aea2', ts: 1.5, gates: [[2, '麻布十番商店街'], [138, '麻布十番商店街']] });
      spot('麻布十番商店街', [-1900, -168, -1760, -132], '麻布十番', '🏮', '老舗と新しい店がまじりあう下町風の商店街。坂の多い麻布の谷あいにあり、夏の納涼まつりはたくさんの人でにぎわう', -1830, -150);
    }

    // ===== 白金台: 明治学院 (記念館・インブリー館・礼拝堂) =====
    {
      const R = [-1626, 994, -1574, 1046];
      site(R, '#a8b090');
      const RB = LM_MAT('KO_MGBRICK', (x, y) => { x.fillStyle = '#a8503a'; x.fillRect(0, 0, 32, 32); x.fillStyle = '#8a3e2c'; for (let j = 0; j < 32; j += 3) x.fillRect(0, j, 32, 1); x.fillStyle = '#e8e2d4'; for (const wx of [5, 19]) { x.fillRect(wx, 8, 8, 14); y.fillStyle = rnd() < 0.4 ? '#ffd8a0' : '#000'; y.fillRect(wx + 1, 9, 6, 12); } });
      pushPrism(RB, 'ROOF', rectPoly(-1620, 1000, -1598, 1014), 0, 8); jRoof('RF0', -1620, 1000, -1598, 1014, 8, 4, { over: 0.6, kind: 'hip' });   // 記念館 (1890年のれんが造)
      pushPrism(C('KO_IMBRIE', { color: 0xf0ece2 }), 'ROOF', rectPoly(-1594, 1000, -1580, 1012), 0, 6.5); jRoof('RF0', -1594, 1000, -1580, 1012, 6.5, 3.6, { over: 0.6, kind: 'hip' });   // インブリー館 (白い木造の洋館)
      pushPrism(RB, 'ROOF', rectPoly(-1616, 1024, -1600, 1042), 0, 7); jRoof('RF0', -1616, 1024, -1600, 1042, 7, 5, { over: 0.4, kind: 'hip' });   // 礼拝堂
      pushPrism(RB, 'ROOF', rectPoly(-1611, 1040, -1605, 1046), 0, 13); bake(lam({ color: 0x5a5a5a }), new THREE.ConeGeometry(3.6, 6, 4).rotateY(Math.PI / 4).translate(-1608, 16, 1043));   // 礼拝堂の塔
      trees(R, 14, ROUND, (x, z) => inR([-1622, 998, -1578, 1016], x, z) || inR([-1618, 1022, -1598, 1046], x, z), 0.9, 1.3);
      spot('明治学院', R, '明治学院', '⛪', 'ヘボン式ローマ字で知られる宣教師ヘボンが築地に開いた学校を源流とし、1887年に白金へ移ってきた。白金のキャンパスには、1890年のれんが造の記念館、宣教師の住まいだったインブリー館 (国の重要文化財)、ヴォーリズ設計の礼拝堂が並ぶ', -1600, 1020);
    }

    // ===== 高輪: 東禅寺 (最初のイギリス公使館跡) =====
    {
      const R = [-1492, 1058, -1448, 1102];
      site(R, '#c2baa6');
      gate([-1480, 1094, -1460, 1100], 5.5, 'RF2', 3);
      hall([-1486, 1064, -1454, 1082], 'WOOD', 0.6, 6, 'RF2', 5.6);
      pushPrism('TKSTONE', 'TKSTONE', rectPoly(-1488, 1062, -1452, 1084), 0, 0.6);
      pushPrism('TKSTONE', 'TKSTONE', rectPoly(-1457, 1088, -1495.6, 1090), 0, 2.2);   // 公使館跡の碑
      trees(R, 10, PINES, (x, z) => inR([-1490, 1060, -1450, 1086], x, z) || Math.abs(x + 1510) < 12 && z > 1086);
      spot('東禅寺 (最初のイギリス公使館跡)', R, '東禅寺', '🇬🇧', '幕末、日本で最初のイギリス公使館が置かれた寺。初代公使オールコックがここを宿舎とし、1861年には攘夷派の浪士に襲われる「東禅寺事件」も起きた', -1470, 1074);
    }
    // ===== 赤坂: 赤坂氷川神社 (8代将軍吉宗が建てた社殿が残る) と勝海舟邸跡 =====
    {
      const R = [-1792, -1172, -1734, -1108];
      site(R, '#c2baa6');
      myojinTorii(-1763, -1112, true, 5.5, 6, STONE, 0.34);
      tiles(-1767, -1140, -1759, -1108, '#d2c8b0', '#c0b69e', 1.4);
      pushPrism('TKSTONE', 'TKSTONE', rectPoly(-1782, -1166, -1744, -1142), 0, 0.8);
      const HK = LM_MAT('KO_HIKAWA', (x, y) => { x.fillStyle = '#c03a2a'; x.fillRect(0, 0, 32, 32); x.fillStyle = '#1e1a18'; x.fillRect(0, 0, 32, 3); x.fillRect(0, 29, 32, 3); for (let i = 0; i < 32; i += 8) x.fillRect(i, 0, 2, 32); y.fillStyle = '#000'; y.fillRect(0, 0, 32, 32); });   // 朱と黒の漆塗り
      hall([-1778, -1162, -1748, -1146], HK, 0.8, 5.5, 'RF_COPPER', 5);
      GINKGO.push([-1745, -1126, 2.2]); solid(-1746, -1127, -1744, -1125, 0, 8);   // 大イチョウ
      pushPrism('TKSTONE', 'TKSTONE', rectPoly(-1785, -1122, -1782, -1120), 0, 0.7);   // 力石
      trees(R, 10, ROUND, (x, z) => inR([-1784, -1168, -1742, -1140], x, z) || Math.abs(x + 1763) < 7 || Math.hypot(x + 1745, z + 1126) < 6, 1, 1.3);
      spot('赤坂氷川神社', R, '赤坂氷川神社', '⛩', '8代将軍徳川吉宗の命で1730年にこの地へ移された神社。そのとき建てられた社殿が、安政の大地震・関東大震災・東京大空襲をくぐり抜けて江戸時代の姿のまま残る。倹約で知られる吉宗らしい質素なつくりだが、朱と黒の漆を組み合わせた工夫も見られる', -1763, -1140);
      SPOT_AREAS.unshift(['大イチョウ (赤坂氷川神社)', -1752, -1133, -1738, -1119]);
      LM_NOTES['大イチョウ (赤坂氷川神社)'] = '高さ25m、推定樹齢400年のイチョウの巨木。秋には境内が黄色に染まる';
      // 勝海舟邸跡 (勝海舟と坂本龍馬の師弟の像)
      const K = [-1732, -1188, -1708, -1162];
      site(K, '#bdb6a6');
      acStatue(-1724, -1172, 0, 1.1, Math.PI, WALL.BRONZE, 'stand', { w: 1.6, h: 1, mat: 'TKSTONE' });
      acStatue(-1716, -1174, 0, 1.15, Math.PI, WALL.BRONZE, 'wave', { w: 1.6, h: 1, mat: 'TKSTONE' });
      spot('勝海舟邸跡', K, '勝海舟邸跡', '🗿', '幕末から明治にかけて勝海舟が住んだ屋敷の跡。坂本龍馬が勝を訪ねて弟子入りしたことにちなみ、二人の師弟の銅像が立っている', -1720, -1175);
    }
    bakeFlush();
  },
});
