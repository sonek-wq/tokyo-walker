/* 皇居 (江戸城の西の丸・吹上) の作り込み
   皇居の森 (stations/jy01_tokyo.js: x -1000〜-680, z -2200〜-1500) の中と、まわりのお濠・門
   - 宮殿 (長和殿・正殿・豊明殿・連翠) と宮殿東庭 … 二重橋 (正門) から入った先
   - 宮内庁庁舎 … 坂下門の内側
   - 東側: 坂下門・蛤濠・桔梗門 (内桜田門)・桔梗濠・桜田巽櫓
   - 西側: 半蔵門 (新宿通りの突き当たり) と、その北の半蔵濠
   - 北側: 乾門 / 西側の森は吹上御苑 */
REGION({
  name: '皇居',
  towns: [],
  labels: [],
  build(r) {
    const { C, spot, TREE_LISTS } = SL_KIT();
    const clearIn = R => { for (const A of TREE_LISTS) { const keep = A.filter(p => !inR(R, p[0], p[1], 2)); A.length = 0; A.push(...keep); } };
    const SHIRO = C('KK_SHIRO', { color: 0xf0ece2 }), TIMBER = C('KK_TIMBER', { color: 0x3a2e26 });
    // お濠 (水面と、歩けない範囲)
    const moat = (x0, z0, x1, z1) => {
      LM_ZONES.push(rectPoly(x0, z0, x1, z1)); clearIn([x0, z0, x1, z1]);
      fr(x0, z0, x1, z1, '#5a6a50'); fr(x0 + 1.5, z0 + 1.5, x1 - 1.5, z1 - 1.5, '#2f5f66');
      const alongZ = z1 - z0 > x1 - x0;
      if (alongZ) for (let z = z0 + 5; z < z1 - 3; z += 5) PONDS.push([(x0 + x1) / 2, z, (x1 - x0) / 2 - 1.5, 6]);
      else for (let x = x0 + 5; x < x1 - 3; x += 5) PONDS.push([x, (z0 + z1) / 2, 6, (z1 - z0) / 2 - 1.5]);
    };
    // 石垣 (上は芝)
    const ishigaki = (x0, z0, x1, z1, h) => { if (x1 - x0 > 0.2 && z1 - z0 > 0.2) pushPrism('ISHIGAKI', 'GRASSTOP', rectPoly(x0, z0, x1, z1), 0, h); };
    // 渡櫓門: 石垣のあいだの通路 (pass 方向に抜ける) の上に白壁の櫓
    const yaguraMon = (cx, cz, alongX, w, d) => {
      const R = (a0, b0, a1, b1) => alongX ? rectPoly(cx + b0, cz + a0, cx + b1, cz + a1) : rectPoly(cx + a0, cz + b0, cx + a1, cz + b1);   // a: 門の幅方向, b: 通り抜ける方向
      const span = w / 2 + 7;
      for (const s of [-1, 1]) { const [a0, a1] = s < 0 ? [-span, -w / 2] : [w / 2, span]; pushPrism('ISHIGAKI', null, R(a0, -d / 2, a1, d / 2), 0, 4.5); pushPrism(SHIRO, null, R(a0, -d / 2, a1, d / 2), 4.5, 10); }
      pushPrism(SHIRO, null, R(-w / 2, -d / 2, w / 2, d / 2), 5.5, 10, { bottom: TIMBER });
      for (const s of [-1, 1]) pushPrism(TIMBER, null, R(s * w / 2 - (s > 0 ? 0 : 1), -d / 2, s * w / 2 + (s > 0 ? 1 : 0), d / 2), 0, 5.5);
      const [x0, z0, x1, z1] = alongX ? [cx - d / 2 - 1, cz - span - 1, cx + d / 2 + 1, cz + span + 1] : [cx - span - 1, cz - d / 2 - 1, cx + span + 1, cz + d / 2 + 1];
      jRoof('RF2', x0, z0, x1, z1, 10, 3.8, { over: 1.2 });
    };
    // 高麗門: 2本の太い柱と小さな屋根 (門の両脇は石垣でふさぐ)
    const koraiMon = (cx, cz, alongX, w) => {
      const R = (a0, b0, a1, b1) => alongX ? rectPoly(cx + b0, cz + a0, cx + b1, cz + a1) : rectPoly(cx + a0, cz + b0, cx + a1, cz + b1);
      for (const s of [-1, 1]) pushPrism(TIMBER, TIMBER, R(s * w / 2 - 0.8, -1.2, s * w / 2 + 0.8, 1.2), 0, 6.2);
      pushPrism(TIMBER, TIMBER, R(-w / 2 - 1, -1, w / 2 + 1, 1), 5.4, 6.2, { solid: false });
      const [x0, z0, x1, z1] = alongX ? [cx - 2.4, cz - w / 2 - 2, cx + 2.4, cz + w / 2 + 2] : [cx - w / 2 - 2, cz - 2.4, cx + w / 2 + 2, cz + 2.4];
      jRoof('RF2', x0, z0, x1, z1, 6.2, 2, { over: 0.8 });
    };

    // ===== 東側: 坂下門・蛤濠・桔梗門・桔梗濠・桜田巽櫓 =====
    moat(-684, -1984, -640, -1904);   // 蛤濠
    moat(-684, -2124, -640, -2006);   // 桔梗濠
    fr(-684, -1904, -640, -1884, '#c4baa2'); fr(-684, -2006, -640, -1984, '#c4baa2');   // 門へ渡る土橋
    ishigaki(-692, -2196, -686, -2006, 4); ishigaki(-692, -1984, -686, -1904, 4); ishigaki(-692, -1884, -686, -1880, 4);
    yaguraMon(-689, -1894, true, 10, 8);   // 坂下門 (渡櫓門だけが残る)
    yaguraMon(-689, -1995, true, 10, 8);   // 桔梗門 (内桜田門)
    koraiMon(-662, -1995, true, 10);
    // 桜田巽櫓 (桔梗濠の北の角に立つ二重櫓)
    {
      const [x0, z0, x1, z1] = [-672, -2156, -646, -2130];
      clearIn([x0 - 4, z0 - 4, x1 + 4, z1 + 4]);
      pushPrism('ISHIGAKI', 'GRASSTOP', rectPoly(x0 - 4, z0 - 4, x1 + 4, z1 + 4), 0, 7);
      pushPrism(SHIRO, null, rectPoly(x0, z0, x1, z1), 7, 13); jRoof('RF2', x0 - 1.5, z0 - 1.5, x1 + 1.5, z1 + 1.5, 13, 2.4, { over: 1.2 });
      pushPrism(SHIRO, null, rectPoly(x0 + 5, z0 + 5, x1 - 5, z1 - 5), 14.5, 19); jRoof('RF2', x0 + 3.8, z0 + 3.8, x1 - 3.8, z1 - 3.8, 19, 3, { over: 1.2 });
      for (const [a, b] of [[x0 + 6, z1 + 0.05], [x1 - 6, z1 + 0.05]]) mesh(new THREE.BoxGeometry(2, 1.2, 0.2), WALL.LM_BLACK, a, 10, b);
      SPOT_AREAS.unshift(['桜田巽櫓', x0 - 5, z0 - 5, x1 + 5, z1 + 5]);
    }
    tiles(-740, -1898, -692, -1890, '#cfc6b0', '#bdb49e', 1.6);   // 坂下門から宮内庁へ
    tiles(-730, -1999, -692, -1991, '#cfc6b0', '#bdb49e', 1.6);   // 桔梗門から中へ
    tiles(-692, -1898, -640, -1890, '#cfc6b0', '#bdb49e', 1.6); tiles(-692, -1999, -640, -1991, '#cfc6b0', '#bdb49e', 1.6);

    // ===== 西側: 半蔵門と半蔵濠 =====
    moat(-1040, -2196, -1006, -1902);   // 半蔵濠 (半蔵門の土橋の北)
    fr(-1040, -1902, -1006, -1880, '#c4baa2');   // 土橋 (南は桜田濠)
    ishigaki(-1004, -2196, -998, -1897, 4); ishigaki(-1004, -1883, -998, -1844, 4);
    koraiMon(-1001, -1890, true, 11);   // いまは和田倉門から移した高麗門だけが立つ
    tiles(-1006, -1894, -960, -1886, '#cfc6b0', '#bdb49e', 1.6);

    // ===== 北側: 乾門 =====
    ishigaki(-998, -2203, -886, -2197, 3); ishigaki(-874, -2203, -692, -2197, 3);
    koraiMon(-880, -2200, false, 11);
    tiles(-886, -2214, -874, -2150, '#cfc6b0', '#bdb49e', 1.6);   // 乾通り

    // ===== 宮殿と宮殿東庭 =====
    {
      const PAL = LM_MAT('KK_PALACE', (x, y) => {   // 白っぽい壁に、こげ茶の柱と大きなガラス
        x.fillStyle = '#e4ddcc'; x.fillRect(0, 0, 32, 32); y.fillStyle = '#000'; y.fillRect(0, 0, 32, 32);
        x.fillStyle = '#4a3a2e'; for (let i = 0; i < 32; i += 8) x.fillRect(i, 0, 1.5, 32);
        x.fillStyle = '#3e4a52'; for (let i = 2; i < 32; i += 8) x.fillRect(i, 8, 5, 18); y.fillStyle = '#ffe8c0'; for (let i = 2; i < 32; i += 8) if (rnd() < 0.5) y.fillRect(i, 8, 5, 18);
      });
      const area = [-905, -1845, -748, -1655];
      clearIn(area);
      fr(...area, '#9aa278');
      // 宮殿東庭 (一般参賀の広場) と、二重橋からの道
      fr(-800, -1815, -752, -1685, '#d8d2c0'); tiles(-752, -1745, -690, -1735, '#d8d2c0', '#c8c2b0', 1.6);
      const hallB = (x0, z0, x1, z1, h, rh) => { pushPrism('TKSTONE', 'TKSTONE', rectPoly(x0 - 1, z0 - 1, x1 + 1, z1 + 1), 0, 1); pushPrism(PAL, 'CONC', rectPoly(x0, z0, x1, z1), 1, h); jRoof('RF_COPPER', x0 - 2.5, z0 - 2.5, x1 + 2.5, z1 + 2.5, h, rh, { over: 2.5, kind: 'irimoya' }); };
      hallB(-822, -1820, -804, -1680, 9, 4);    // 長和殿 (東庭に面した長い棟)
      // 長和殿のベランダ (一般参賀で皇族方が立たれる)
      pushPrism('glass', 'CONC', rectPoly(-804, -1764, -801, -1736), 4.5, 8);
      pushPrism('CONC', 'CONC', rectPoly(-804, -1766, -800, -1734), 4, 4.5);
      hallB(-872, -1772, -836, -1728, 11, 5.5);   // 正殿
      hallB(-884, -1832, -836, -1792, 9, 4.5);    // 豊明殿
      hallB(-872, -1712, -842, -1688, 8, 3.5);    // 連翠
      hallB(-902, -1770, -880, -1730, 7, 3);      // 表御座所
      fr(-834, -1786, -824, -1714, '#c8c0a8'); fr(-878, -1726, -838, -1716, '#6a8a4a');   // 中庭
      for (const [x, z] of [[-880, -1676], [-860, -1666], [-840, -1676], [-890, -1700], [-760, -1668], [-772, -1832], [-790, -1836]]) PINES.push([x, z, rr(1, 1.3)]);
      LM_PEOPLE.push([[-790, -1744, -700, -1744], 4]);
      SPOT_AREAS.unshift(['長和殿 (宮殿)', -824, -1822, -799, -1678], ['宮殿東庭', -799, -1815, -752, -1685]);
      spot('宮殿 (皇居)', area, '宮殿', '🏯', '1945年に焼けた明治宮殿に代わり、1968年に完成した。儀式や行事が行われる正殿・豊明殿・長和殿などからなり、外国の大使が信任状を差し出す儀式などもここで行われる', -850, -1750);
    }

    // ===== 宮内庁庁舎 =====
    {
      const R = [-792, -1918, -742, -1872];
      clearIn(R);
      const KU = LM_MAT('KK_KUNAI', (x, y) => { x.fillStyle = '#d8d0bc'; x.fillRect(0, 0, 32, 32); y.fillStyle = '#000'; y.fillRect(0, 0, 32, 32); for (let j = 3; j < 32; j += 8) for (let i = 2; i < 32; i += 5) { x.fillStyle = '#4a5058'; x.fillRect(i, j, 3, 4); y.fillStyle = rnd() < 0.45 ? '#ffe8c0' : '#000'; y.fillRect(i, j, 3, 4); } });
      pushPrism(KU, 'CONC', rectPoly(-790, -1916, -744, -1874), 0, 15);
      pushPrism(KU, 'CONC', rectPoly(-776, -1904, -758, -1886), 15, 21);   // 中央の塔屋
      pushPrism('CONC', 'CONC', rectPoly(-747, -1900, -742, -1888), 0, 5);   // 車寄せ
      spot('宮内庁庁舎', R, '宮内庁', '🏛', '1935年に建てられた建物。戦後の1952年から1969年まで、3階が仮の宮殿として使われていた', -767, -1895);
    }

    // ===== 名所の名前と説明 =====
    SPOT_AREAS.unshift(['坂下門', -700, -1904, -640, -1884], ['桔梗門 (内桜田門)', -700, -2006, -640, -1984], ['蛤濠', -684, -1984, -640, -1904], ['桔梗濠', -684, -2124, -640, -2006],
      ['半蔵門', -1040, -1902, -996, -1878], ['半蔵濠', -1040, -2196, -1006, -1902], ['乾門', -896, -2214, -864, -2190]);
    SPOT_AREAS.push(['吹上御苑', -998, -2196, -860, -1856]);
    LM_LABELS.push(['半蔵門', -1012, -1876, '⛩'], ['坂下門', -680, -1878, '⛩'], ['桔梗門', -660, -2012, '⛩', '桔梗門 (内桜田門)'], ['宮殿', -840, -1700, '🏯', '宮殿 (皇居)'], ['乾門', -880, -2218, '⛩'], ['巽櫓', -659, -2165, '🏯', '桜田巽櫓']);
    Object.assign(LM_NOTES, {
      '長和殿 (宮殿)': '東庭に面した宮殿の長い棟。新年 (1月2日) と天皇誕生日の一般参賀では、天皇陛下と皇族方がこのベランダに立たれ、東庭に集まった人たちにお言葉がある',
      '宮殿東庭': '長和殿の前に広がる広場。一般参賀の日は大勢の人で埋まる',
      '坂下門': '西の丸の坂の下にあったことが名の由来。1862年、老中・安藤信正がこの門の外で水戸浪士に襲われた「坂下門外の変」の舞台。門を入ると宮殿と宮内庁がある',
      '桔梗門 (内桜田門)': '外桜田門 (桜田門) に対して内桜田門とも呼ばれる。江戸城を最初に築いた太田道灌の家紋の桔梗が名の由来ともいわれる。いまは皇居一般参観の入口になっている',
      '蛤濠': '坂下門の北に広がる内濠',
      '桔梗濠': '1614年に造られた江戸城の内濠。向かいに桜田巽櫓がそびえる',
      '桜田巽櫓': '本丸から見て東南 (辰巳=巽) の方角にあることが名の由来。富士見櫓・伏見櫓とともに、江戸城に今も残る3つの隅櫓のひとつ',
      '半蔵門': '甲州街道 (いまの新宿通り) の突き当たりにある、江戸城の裏手の門。名前は門の内に住んだとされる服部半蔵に由来する。いまは天皇陛下や皇族方がふだんの出入りに使う門で、一般の人は通れない',
      '半蔵濠': '半蔵門の土橋をはさんで、北が半蔵濠、南が桜田濠',
      '乾門': '皇居の北西 (乾の方角) の門。春と秋に行われる「乾通りの通り抜け」では、ここが出口になる',
      '吹上御苑': '皇居の西側に広がる深い森。天皇陛下のお住まいの御所があり、ふだんは入れない',
    });
    LM_NOTES['皇居'] = (LM_NOTES['皇居'] ? LM_NOTES['皇居'] + '。' : '') + 'まわりを囲むお濠ぞいの歩道は「皇居ラン」のランナーにも人気';
    bakeFlush();
  },
});
