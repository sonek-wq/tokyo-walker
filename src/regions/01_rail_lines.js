const RLN = {
  // 角を丸める (半径 r m くらいの曲線)。y と flag は直線で補間
  round(P, r = 40) {
    const out = [P[0]];
    for (let i = 1; i < P.length - 1; i++) {
      const a = P[i - 1], b = P[i], c = P[i + 1], la = Math.hypot(b[0] - a[0], b[1] - a[1]), lc = Math.hypot(c[0] - b[0], c[1] - b[1]);
      const ux = (b[0] - a[0]) / la, uz = (b[1] - a[1]) / la, vx = (c[0] - b[0]) / lc, vz = (c[1] - b[1]) / lc, turn = Math.acos(Math.max(-1, Math.min(1, ux * vx + uz * vz)));
      if (turn < 0.05) { out.push(b); continue; }
      const d = Math.min(r * Math.tan(turn / 2), la * 0.45, lc * 0.45), p0 = [b[0] - ux * d, b[1] - uz * d], p1 = [b[0] + vx * d, b[1] + vz * d];
      const n = Math.max(2, Math.ceil(turn / 0.12));
      for (let k = 0; k <= n; k++) {
        const t = k / n, m = 1 - t, x = m * m * p0[0] + 2 * m * t * b[0] + t * t * p1[0], z = m * m * p0[1] + 2 * m * t * b[1] + t * t * p1[1];
        out.push([x, z, b[2] + (k / n - 0.5) * 0, b[3] || 0]);
      }
    }
    out.push(P[P.length - 1]);
    return out.map(p => [p[0], p[1], p[2] ?? 0, p[3] || 0]);
  },
  // 折れ線を横にずらす (右 = 進む向きの (-tz, tx) 側が +)
  offset(P, d) {
    return P.map((p, i) => {
      const a = P[Math.max(0, i - 1)], b = P[Math.min(P.length - 1, i + 1)], l = Math.hypot(b[0] - a[0], b[1] - a[1]) || 1;
      let nx = -(b[1] - a[1]) / l, nz = (b[0] - a[0]) / l;
      if (i > 0 && i < P.length - 1) {   // 角では前後の法線の平均 (角が尖っても幅がほぼ保たれる)
        const l1 = Math.hypot(p[0] - a[0], p[1] - a[1]) || 1, l2 = Math.hypot(b[0] - p[0], b[1] - p[1]) || 1;
        const n1 = [-(p[1] - a[1]) / l1, (p[0] - a[0]) / l1], n2 = [-(b[1] - p[1]) / l2, (b[0] - p[0]) / l2], s = [n1[0] + n2[0], n1[1] + n2[1]], ls = Math.hypot(...s) || 1, c = Math.max(0.5, (s[0] * n1[0] + s[1] * n1[1]) / ls);
        nx = s[0] / ls / c; nz = s[1] / ls / c;
      }
      return [p[0] + nx * d, p[1] + nz * d, p[2], p[3] || 0];
    });
  },
  // 折れ線上で (x, z) にいちばん近い点から、横に d ずらした点
  beside(P, x, z, d = 0) {
    let best = null, bd = Infinity;
    for (let i = 0; i < P.length - 1; i++) {
      const [ax, az] = P[i], [bx, bz] = P[i + 1], dx = bx - ax, dz = bz - az, L2 = dx * dx + dz * dz || 1, t = Math.max(0, Math.min(1, ((x - ax) * dx + (z - az) * dz) / L2));
      const px = ax + dx * t, pz = az + dz * t, dd = Math.hypot(x - px, z - pz); if (dd < bd) { const l = Math.sqrt(L2); bd = dd; best = [px - dz / l * d, pz + dx / l * d]; }
    }
    return best;
  },
  // 山手線の環に沿った点の列 (from → to。ext0 / ext1 で両端を延ばす)。lat は環の外側が +
  ringS: n => typeof n === 'number' ? n : STN.find(s => s.name === n).s,
  ring(from, to, lat, y, e0 = 0, e1 = 0, flag = 0, step = 20) {
    let s0 = RLN.ringS(from), s1 = RLN.ringS(to); if (s1 - s0 > RING_LEN / 2) s1 -= RING_LEN; if (s0 - s1 > RING_LEN / 2) s1 += RING_LEN;
    const dir = Math.sign(s1 - s0) || 1, a = s0 - dir * e0, b = s1 + dir * e1, n = Math.max(1, Math.ceil(Math.abs(b - a) / step)), out = [];
    for (let k = 0; k <= n; k++) { const q = ringAt(wrapS(a + (b - a) * k / n)); out.push([q.x + q.nx * lat, q.z + q.nz * lat, y, flag]); }
    return out;
  },
  ringPt(name, lat, ds = 0) { const q = ringAt(wrapS(RLN.ringS(name) + ds)); return [q.x + q.nx * lat, q.z + q.nz * lat]; },
};
