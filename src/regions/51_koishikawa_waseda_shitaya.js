/* 名所が手薄だった町の作り込み (その2)
   - 小石川: 伝通院 (家康の母・於大の方の寺) / 春日: 文京シビックセンター (高さ105mの展望ラウンジへエレベーター)
   - 白山: 白山神社 (富士塚と6月のあじさい)
   - 早稲田南: 漱石山房記念館・夏目坂 / 馬場下: 穴八幡宮 (楼門と一陽来復)
   - 東上野 (稲荷町): 下谷神社 (寄席発祥の地) */
REGION({
  name: '小石川・早稲田南・稲荷町',
  towns: [['小石川', -1018, -3420], ['春日', -715, -3240], ['白山', -650, -3960], ['早稲田南町', -2073, -2930], ['馬場下町', -2200, -3175], ['東上野 (稲荷町)', 664, -3320]],
  labels: [],
  build(r) {
    const { C, site, spot, sign, SHU, STONE, plasterWood, windows, hall, gate, fujizuka } = SL_KIT();
    const trees = (R, n, list = ROUND, avoid = null, s0 = 0.8, s1 = 1.2, base) => {
      for (let k = 0; k < n; k++) { const x = rr(R[0] + 2, R[2] - 2), z = rr(R[1] + 2, R[3] - 2); if (avoid && avoid(x, z)) continue; list.push(base === undefined ? [x, z, rr(s0, s1)] : [x, z, rr(s0, s1), base]); }
    };

    // ===== 伝通院 (無量山 傳通院 寿経寺) =====
    {
      const R = [-1050, -3520, -985, -3450];
      site(R, '#c4bca6');
      tiles(-1022, -3470, -1012, -3450, '#d2c8b0', '#c0b69e', 1.4);
      // 山門 (2012年に再建された二層の楼門)
      for (const sx of [-1, 1]) pushPrism('WOOD', 'WOOD', rectPoly(-1017 + sx * 6 - 2, -3462, -1017 + sx * 6 + 2, -3456), 0, 5);
      pushPrism('WOOD', 'WOOD', rectPoly(-1023, -3462, -1011, -3456), 4, 5);
      pushPrism('WOOD', 'WOOD', rectPoly(-1023, -3461, -1011, -3457), 5, 8.5);
      jRoof('RF2', -1025, -3463, -1009, -3455, 5, 1.2, { over: 1, kind: 'hip' }); jRoof('RF2', -1024, -3462, -1010, -3456, 8.5, 3.2, { over: 1.4, kind: 'irimoya' });
      hall([-1036, -3510, -998, -3484], 'WOOD', 0.8, 7, 'RF2', 6.5);   // 本堂
      pushPrism('TKSTONE', 'TKSTONE', rectPoly(-1038, -3512, -996, -3482), 0, 0.8);
      for (const [x, z] of [[-1046, -3516], [-1042, -3516], [-990, -3516]]) pushPrism('TKSTONE', 'TKSTONE', rectPoly(x - 0.7, z - 0.7, x + 0.7, z + 0.7), 0, 2.6);   // 墓所の宝篋印塔
      STONE_LANTERNS.push([-1022, -3474], [-1012, -3474]);
      trees(R, 14, GINKGO, (x, z) => inR([-1040, -3514, -994, -3452], x, z) && Math.abs(x + 1017) < 22);
      spot('伝通院', R, '伝通院', '🛕', '1415年に開かれた浄土宗の寺。徳川家康が母・於大の方をここに葬り、その法名「伝通院」が寺の名前になった。千姫など徳川家ゆかりの女性の墓が多く、江戸時代には学僧1000人あまりが学ぶ学問所でもあった', -1017, -3490);
    }

    // ===== 文京シビックセンター (区役所の高層ビル。高さ105mの展望ラウンジ) =====
    {
      const R = [-738, -3208, -692, -3162], X = -715, Z = -3185;
      site(R, '#bdb8ae');
      pushPrism(windows('KB_CIVIC', '#cfd4d8', '#3a4a5a', 4, 6), 'ROOF', rectPoly(X - 16, Z - 12, X + 16, Z + 12), 0, 100);
      pushPrism('CONC', 'CONC', rectPoly(X - 16, Z - 12, X + 16, Z + 12), 100, 104.5);
      for (const [x0, z0, x1, z1] of [[X - 16, Z - 12, X + 16, Z - 11.6], [X - 16, Z + 11.6, X + 16, Z + 12], [X - 16, Z - 12, X - 15.6, Z + 12], [X + 15.6, Z - 12, X + 16, Z + 12]]) pushPrism('glass', 'glass', rectPoly(x0, z0, x1, z1), 104.5, 108);
      pushPrism('CONC', 'ROOF', rectPoly(X - 16.4, Z - 12.4, X + 16.4, Z + 12.4), 108, 109);
      roofLift([X, Z + 14], [X, 104.5, Z], '展望ラウンジ (高さ105m) に着いた', '1階におりた', { r: 5, topR: 12, upPrompt: 'E　エレベーターで展望ラウンジへ' });
      sign(X, Z + 12.4, 1, '文京シビックセンター', 12, 7);
      spot('文京シビックセンター', R, 'シビックセンター', '🏢', '文京区役所などが入る高層ビル。高さ105mの展望ラウンジからは、東京ドームや東京スカイツリー、天気がよければ富士山まで見わたせる', X, Z);
      LM_HEIGHT_AREAS.unshift(['文京シビックセンター 展望ラウンジ', (x, z, y) => y > 100 && inR([X - 16, Z - 12, X + 16, Z + 12], x, z)]);
      LM_NOTES['文京シビックセンター 展望ラウンジ'] = '一般に公開されている展望スポットの中では都内でも高いほう。真下に東京ドームと小石川後楽園が見える';
    }

    // ===== 白山神社 (富士塚とあじさい) =====
    {
      const R = [-675, -4045, -625, -3995];
      site(R, '#c2baa6');
      myojinTorii(-650, -3999, true, 5, 5.6, STONE, 0.32);
      stairs([-654, -4010, -646, -4002], 1.6, 'z-');
      pushPrism('ISHIGAKI', 'TKSTONE', rectPoly(-668, -4040, -632, -4010), 0, 1.6);
      hall([-662, -4034, -638, -4020], 'WOOD', 1.6, 4.6, 'RF_COPPER', 4.2);
      fujizuka(-631, -4034, 5, 4, 0);
      const AJ = MONTH === 6 ? [0x4a6ad8, 0x8a5ad0, 0xd86aa8, 0x6a9ae8] : [0x3e6a34, 0x4a7a3a];
      for (let k = 0; k < 60; k++) { const x = rr(-674, -626), z = rr(-4044, -3996); if (inR([-669, -4041, -631, -4009], x, z) || Math.abs(x + 650) < 5 || Math.hypot(x + 631, z + 4034) < 6) continue; bake(lam({ color: pick(AJ) }), new THREE.DodecahedronGeometry(rr(0.6, 0.9), 0).translate(x, 0.6, z)); }
      trees(R, 6, ROUND, (x, z) => inR([-670, -4042, -630, -4004], x, z) || Math.abs(x + 650) < 5);
      spot('白山神社', R, '白山神社', '⛩', '平安時代に加賀 (石川県) の白山神社を迎えたのが始まりと伝わる神社。6月の「文京あじさいまつり」では、境内からとなりの白山公園まで約3000株のあじさいが咲き、ふだんは入れない富士塚もあじさいに包まれる', -650, -4025);
    }

    // ===== 漱石山房記念館と夏目坂 =====
    {
      const R = [-2096, -2992, -2050, -2948];
      site(R, '#b8b2a2');
      pushPrism(windows('KB_SOSEKI', '#3a3a3a', '#a0a8b0', 8, 6), 'ROOF', rectPoly(-2090, -2986, -2066, -2964), 0, 8);   // 黒い外壁のモダンな記念館
      const VR = plasterWood('KB_SANBO', '#e8e2d2', '#5a4a3a');
      pushPrism(VR, 'ROOF', rectPoly(-2064, -2986, -2054, -2972), 0.4, 3.4); jRoof('RF2', -2064, -2986, -2054, -2972, 3.4, 1.6, { over: 0.8, kind: 'hip' });   // 漱石山房のベランダ式の書斎 (再現)
      fe(-2070, -2956, 8, 5, '#7a9a54'); trees([-2080, -2962, -2056, -2950], 4, ROUND, null, 0.6, 0.8);
      pushPrism('TKSTONE', 'TKSTONE', rectPoly(-2063, -2956, -2061, -2954), 0, 1.4);   // 猫塚
      spot('漱石山房記念館', R, '漱石山房記念館', '🐈', '夏目漱石が亡くなるまでの約9年間を過ごした家「漱石山房」の跡に建つ記念館。漱石はここで「三四郎」や「こころ」を書いた。館内には書斎が再現され、庭には漱石の猫をしのぶ「猫塚」が残る');
      SPOT_AREAS.unshift(['夏目坂', -2190, -3110, -2140, -3000]);
      LM_NOTES['夏目坂'] = '漱石の父・夏目直克が、自分の家の前の坂を「夏目坂」と呼んだのが名前のはじまり。この坂の下のあたりが漱石の生まれた場所';
    }

    // ===== 穴八幡宮 (楼門と社殿。冬至から節分まで「一陽来復」のお守り) =====
    {
      const R = [-2226, -3162, -2174, -3108];
      site(R, '#c2baa6');
      myojinTorii(-2200, -3112, true, 6, 6.6, SHU, 0.38);
      stairs([-2205, -3126, -2195, -3116], 2, 'z-');
      pushPrism('ISHIGAKI', 'TKSTONE', rectPoly(-2222, -3158, -2178, -3126), 0, 2);
      gate([-2210, -3132, -2190, -3126], 7, 'RF_COPPER', 3.6);   // 楼門 (随神門)
      hall([-2214, -3154, -2186, -3138], SHU, 2, 6, 'RF_COPPER', 5);
      if (MONTH === 12 || MONTH === 1) LM_PEOPLE.push([[-2200, -3100, -2200, -3150, 0], 12]);   // お守りを求める行列
      trees(R, 8, GINKGO, (x, z) => inR([-2220, -3160, -2180, -3114], x, z));
      spot('穴八幡宮', R, '穴八幡宮', '⛩', '1062年、源義家が奥州からの凱旋の途中に兜と太刀を納めてまつったのが始まりとされる。冬至から節分までだけ授かれる「一陽来復」のお守りが有名で、その時期には長い行列ができる', -2200, -3140);
    }

    // ===== 下谷神社 (東京でいちばん古いお稲荷さんのひとつ。寄席発祥の地) =====
    {
      const R = [645, -3386, 685, -3344];
      site(R, '#c2baa6');
      myojinTorii(665, -3348, true, 5, 5.4, lam({ color: 0xc8402a }), 0.3);
      pushPrism('TKSTONE', 'TKSTONE', rectPoly(651, -3380, 679, -3362), 0, 0.6);
      hall([653, -3378, 677, -3364], 'WOOD', 0.6, 4.6, 'RF_COPPER', 4.4);
      pushPrism('TKSTONE', 'TKSTONE', rectPoly(674, -3352, 676.5, -3350.8), 0, 2.4);   // 寄席発祥の地の碑
      STONE_LANTERNS.push([661, -3356], [669, -3356]);
      trees(R, 5, ROUND, (x, z) => inR([649, -3382, 681, -3346], x, z) && Math.abs(x - 665) < 8);
      spot('下谷神社', R, '下谷神社', '🦊', '730年創建と伝わる、都内でもとても古いお稲荷さん。昔は「下谷稲荷」と呼ばれ、地名「稲荷町」のもとになった。1798年、のちの初代三笑亭可楽がこの境内で寄席を開いたことから「寄席発祥の地」の碑が立つ', 665, -3368);
    }
    bakeFlush();
  },
});
